  HBA1C_RISK_PROB:'ความเสี่ยงน้ำตาลสะสม (HbA1c)', MFBG_RISK_PROB:'ความเสี่ยงน้ำตาลในเลือด',
  HEALTH_SCORE:'คะแนนสุขภาพโดยรวม',
