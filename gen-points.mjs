  BP_SYSTOLIC:'ความดันโลหิตตัวบน', BP_DIASTOLIC:'ความดันโลหิตตัวล่าง', TEMPERATURE_SENSOR:'อุณหภูมิร่างกาย',
  HRV_SDNN:'ความแปรปรวนหัวใจ (HRV)', BP_RPP:'ภาระงานของหัวใจ', VITALITY:'ดัชนีความกระปรี้กระเปร่า',
  MSI:'ดัชนีความเครียด', SLEEP_QUALITY:'ดัชนีคุณภาพการนอน', ANXIETY_INDEX:'ดัชนีความวิตกกังวล',
